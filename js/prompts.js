  for (const o of years.values()) if (o.where.length >= 2) out.push(o);
  out.sort((a, b) => b.where.length - a.where.length);
  return out.slice(0, 30).map(x => `- ${x.label}: ${x.where.map(n => `「${n}」`).join(", ")}`).join("\n");
